const S1 = liveSessionId('s1')
const image: Image = { mime: 'image/png', name: 'shot.png', path: '/uploads/1.png' }
const typed = (text: string, images: Image[] = []): Prompt => ({ images, kind: 'typed', pasted: [], text })

const row = (id: string, status: PendingStatus, user = id): PendingRow => ({
  admission_id: admissionId(id),
  input_id: inputId(`in-${id}`),
  status,
  user
})

/** A PromptQueue on a fake gateway, and what it did to the app: notices, steers, restores and sends. */
function setup({ busy = true, canDrain = false, sid = S1 }: { busy?: boolean; canDrain?: boolean; sid?: LiveSessionId | null } = {}) {
  const gw = new FakeGateway({
    replies: {
      'prompt.cancel': () => ({ status: 'terminal' }),
      'prompt.submit': p => ({ admission_id: `adm-${String(p['text'])}` }),
      'session.resume': () => ({ execution_generation: 1 }),
      'session.steer': () => ({ status: 'queued' })
    }
  })
  const log: string[] = []
  const state = { busy, canDrain, sid }
  const host: QueueHost = {
    busy: () => state.busy,
    canDrain: () => state.canDrain,
    changed: () => undefined,
    expanded: (_sid, prompt) => Promise.resolve(prompt),
    gw: gw.client,
    restore: prompt => log.push(`restore ${prompt.text}`),
    send: prompt => log.push(`send ${prompt.text}`),
    ticket: () => sessionTicket(() => state.sid, new AbortController().signal),
    transcript: {
      notice: (text, tone) => log.push(`${tone ?? 'info'}: ${text}`),
      steer: text => log.push(`steer ${text}`)
    }
  }

  return { gw, log, queue: new PromptQueue(host), settle: () => settle(gw), state }
}

/** Admits `text` into the shared gateway's queue; prompt.submit names it `adm-<text>`. */
async function admitted(t: ReturnType<typeof setup>, text: string, images: Image[] = []) {
  await t.queue.admit(S1, typed(text, images))
}

describe('PromptQueue', () => {
  it('lists the held prompts first, then the FIFO, then admissions it does not list yet', async () => {
    const t = setup()
    t.queue.hold(typed('held'))
    t.queue.hold({ display: '/skill', images: [image], kind: 'command', text: 'the skill body' })
    t.queue.server.update([row('a', 'queued', 'theirs'), row('b', 'unknown', 'lost')])
    await admitted(t, 'mine')
    t.gw.handlers.set('prompt.submit', () => new Promise(() => undefined))
    void t.queue.admit(S1, typed('on its way'))
    await t.settle()

    expect(t.queue.count()).toBe(6)
    expect(t.queue.rows()).toEqual([
      { kind: 'local', steer: true, text: 'held' },
      { kind: 'local', steer: true, text: '/skill\n\n📎 1 image' },
      { kind: 'foreign', note: 'elsewhere', text: 'theirs' },
      { kind: 'foreign', note: 'unknown', text: 'lost' },
      { kind: 'mine', steer: true, text: 'mine' },
      { kind: 'sending', text: 'on its way' }
    ])

    // No turn runs: nothing offers Steer.
    t.state.busy = false
    expect(t.queue.rows().filter(r => 'steer' in r && r.steer)).toEqual([])
  })

  it("offers no Steer on an admission with images, and names another viewer's notice as Hermes does", async () => {
    const t = setup()
    await admitted(t, 'look', [image])
    const footer = '\n\n[INTERNAL NOTIFICATION — generated by the Hermes gateway, not written by a human user.]'
    t.queue.server.update([{ ...row('x', 'queued'), user: `[IMPORTANT: Background process proc_1 exited (exit code 0).${footer}` }])

    expect(t.queue.rows()).toEqual([
      { kind: 'foreign', note: 'elsewhere', text: 'Background command exited' },
      { kind: 'mine', steer: false, text: 'look\n\n📎 1 image' }
    ])
  })

  it('admits with queued: true, and puts a refused admission back in the composer', async () => {
    const t = setup()
    await t.queue.admit(S1, typed('first'))
    expect(t.gw.sent('prompt.submit')).toEqual([{ queued: true, session_id: 's1', submission_id: expect.any(String), text: 'first' }])

    t.gw.handlers.set('prompt.submit', () => {
      throw new Error('queue_full')
    })
    await t.queue.admit(S1, typed('second'))

    expect(t.queue.rows().map(r => r.text)).toEqual(['first'])
    expect(t.log).toEqual(['error: Not queued: queue_full. Your message is back in the composer.', 'restore second'])
  })

  it('on adopt, returns the prompts held for another session to the composer, oldest on top, and keeps the rest', () => {
    const t = setup()
    const s1 = { live: S1, stored: null }
    t.queue.hold(typed('a'))
    t.queue.hold(typed('b'), { kind: 'session', ref: s1 })
    t.queue.hold(typed('c'), { kind: 'session', ref: s1 })
    t.queue.hold(typed('d'), { kind: 'session', ref: { live: S1, stored: storedSessionId('st1') } })

    // The same session again (its runtime id): nothing moves.
    t.queue.adopt({ live: S1, stored: null })
    expect(t.queue.held.map(p => p.text)).toEqual(['a', 'b', 'c', 'd'])
    expect(t.log).toEqual([])

    // Another runtime id with d's stored id (a reattach of d's session): b and c go back.
    t.queue.adopt({ live: liveSessionId('s2'), stored: storedSessionId('st1') })
    expect(t.queue.held.map(p => p.text)).toEqual(['a', 'd'])
    expect(t.log).toEqual(['restore c', 'restore b', 'warning: 2 prompts queued for the last session are back in the composer.'])
  })

  it('dequeues a held prompt into the composer, and withdraws an admission before restoring it', async () => {
    const t = setup()
    t.queue.hold(typed('a'))
    t.queue.hold(typed('b'))
    t.queue.dequeue(1)
    expect(t.queue.held.map(p => p.text)).toEqual(['a'])
    expect(t.log).toEqual(['restore b'])

    await admitted(t, 'mine')
    t.queue.dequeue(1)
    await t.settle()

    expect(t.gw.sent('prompt.cancel')).toEqual([{ admission_id: 'adm-mine', session_id: 's1' }])
    expect(t.queue.count()).toBe(1)
    expect(t.log).toEqual(['restore b', 'restore mine'])
    // Its `cancelled` completion is not the running turn's.
    expect(t.queue.server.settlesQueuedRow({ admission_id: 'adm-mine', outcome: 'cancelled' })).toBe(true)
  })

  it('leaves an admission that started meanwhile, or that is still on its way, where it is', async () => {
    const t = setup()
    await admitted(t, 'mine')
    t.gw.handlers.set('prompt.cancel', () => ({ status: 'started' }))
    t.queue.dequeue(0)
    await t.settle()

    expect(t.queue.rows()).toEqual([{ kind: 'mine', steer: true, text: 'mine' }])
    expect(t.log).toEqual([])

    t.gw.handlers.set('prompt.cancel', () => {
      throw new Error('not_found')
    })
    t.queue.dequeue(0)
    await t.settle()
    expect(t.log).toEqual(['error: Could not take the prompt out of the queue: not_found'])

    // prompt.submit has not answered: nothing names the row to withdraw.
    const u = setup()
    u.gw.handlers.set('prompt.submit', () => new Promise(() => undefined))
    void u.queue.admit(S1, typed('on its way'))
    await u.settle()
    u.queue.dequeue(0)
    u.queue.steer(0)
    await u.settle()
    expect(u.gw.methods('prompt.cancel')).toEqual([])
  })

  it('steers a held prompt into the turn, and keeps one with images', async () => {
    const t = setup()
    t.queue.hold(typed('with image', [image]))
    t.queue.hold(typed('words'))
    t.queue.steer(0)
    t.queue.steer(1)
    await t.settle()

    expect(t.gw.sent('session.steer')).toEqual([{ execution_generation: 1, session_id: 's1', text: 'words' }])
    expect(t.queue.held.map(p => p.text)).toEqual(['with image'])
    expect(t.log).toEqual(['warning: A queued prompt with images cannot steer the turn. It stays queued.', 'steer words'])
  })

  it('puts a held prompt whose steer failed back at its index, and drains', async () => {
    const t = setup()
    t.gw.handlers.set('session.steer', () => ({ status: 'rejected' }))
    t.queue.hold(typed('a'))
    t.queue.hold(typed('b'))
    t.queue.steer(1)
    expect(t.queue.held.map(p => p.text)).toEqual(['a'])
    await t.settle()

    expect(t.queue.held.map(p => p.text)).toEqual(['a', 'b'])
    expect(t.log).toEqual(['warning: The turn ended before the steer landed. It will send as the next prompt.'])

    t.state.canDrain = true
    t.queue.hold(typed('c'))
    t.queue.steer(0)
    await t.settle()
    expect(t.log.slice(1)).toEqual(['warning: The turn ended before the steer landed. It will send as the next prompt.', 'send a'])
    expect(t.queue.held.map(p => p.text)).toEqual(['b', 'c'])
  })

  it('steers an admission once withdrawn, and admits it again at the end when the steer fails', async () => {
    const t = setup()
    await admitted(t, 'first')
    await admitted(t, 'second')
    t.queue.steer(0)
    await t.settle()

    expect(t.gw.sent('session.steer').map(p => p['text'])).toEqual(['first'])
    expect(t.queue.rows().map(r => r.text)).toEqual(['second'])
    expect(t.log).toEqual(['steer first'])

    t.gw.handlers.set('session.steer', () => {
      throw new Error('boom')
    })
    t.queue.steer(0)
    await t.settle()

    expect(t.gw.sent('prompt.submit').map(p => p['text'])).toEqual(['first', 'second', 'second'])
    expect(t.queue.rows().map(r => [r.kind, r.text])).toEqual([['mine', 'second']])
    expect(t.log.at(-1)).toBe('warning: Steer failed: boom. Queued again, at the end.')
  })

  it('does not steer with no turn or no session', () => {
    const t = setup({ busy: false })
    t.queue.hold(typed('a'))
    t.queue.steer(0)
    const u = setup({ sid: null })
    u.queue.hold(typed('a'))
    u.queue.steer(0)

    expect([t.gw.calls, u.gw.calls]).toEqual([[], []])
    expect([t.queue.held.length, u.queue.held.length]).toEqual([1, 1])
  })

  it('drains the oldest held prompt only when the host allows it', () => {
    const t = setup()
    t.queue.hold(typed('a'))
    t.queue.holdFirst(typed('first'))
    t.queue.drain()
    expect(t.log).toEqual([])

    t.state.canDrain = true
    t.queue.drain()
    expect(t.log).toEqual(['send first'])
    expect(t.queue.held.map(p => p.text)).toEqual(['a'])
  })

  it('attaches the startup image to the held head in place, and reports an empty queue', () => {
    const t = setup()
    expect(t.queue.attachToHead(image)).toBe(false)

    const head: Prompt = { images: [], kind: 'app', text: 'What do you see in this image?' }
    t.queue.hold(head)
    expect(t.queue.attachToHead(image)).toBe(true)
    expect(head.images).toEqual([image])
  })
})

/** The dock's queued rows as drawn: icon, title, text, badges and actions. */
function drawn(queued: QueuedRow[], steer = true) {
  const rows = dockNodes(dockContext({ queue: { canSteer: steer, rows: queued } }), dockActions()).flatMap(n => (n instanceof Node && n.props['role'] === 'omp.queue' ? n.toJSON().c ?? [] : []))
  const prop = (n: NodeJson, name: string) => n.p?.[name]

  return rows.map(r => ({
    actions: (r.c ?? []).map(faceJson).flatMap(c => (prop(c, 'role') === 'omp.queue.steer' ? ['steer'] : prop(c, 'role') === 'omp.queue.edit' ? ['edit'] : [])),
    badges: (r.c ?? []).filter(c => c.k === 'badge' && prop(c, 'key') === 'note').map(c => prop(c, 'text')),
    icon: r.c?.filter(c => c.k === 'icon').map(c => prop(c, 'name'))[0],
    title: prop(r, 'title')
  }))
}

describe('the dock’s queued rows', () => {
  it('draws a held row with Edit, and Steer while a turn runs', () => {
    const look = { badges: [], icon: 'corner-down-right', title: 'Queued' }

    expect(drawn([{ kind: 'local', steer: true, text: 'a' }])).toEqual([{ ...look, actions: ['steer', 'edit'] }])
    expect(drawn([{ kind: 'local', steer: true, text: 'a' }], false)).toEqual([{ ...look, actions: ['edit'] }])
  })

  it("draws this pane's admission with Edit, and Steer unless it carries images", () => {
    const look = { badges: [], icon: 'corner-down-right', title: 'Queued' }

    expect(drawn([{ kind: 'mine', steer: true, text: 'a' }])).toEqual([{ ...look, actions: ['steer', 'edit'] }])
    expect(drawn([{ kind: 'mine', steer: false, text: 'a' }])).toEqual([{ ...look, actions: ['edit'] }])
  })

  it('draws an admission on its way with a clock and nothing to act on', () => {
    expect(drawn([{ kind: 'sending', text: 'a' }])).toEqual([{ actions: [], badges: [], icon: 'clock', title: 'Queuing…' }])
  })

  it("draws another window's row with nothing to act on, and flags an unknown outcome", () => {
    expect(drawn([{ kind: 'foreign', note: 'elsewhere', text: 'a' }])).toEqual([
      { actions: [], badges: [], icon: 'corner-down-right', title: 'Queued by another window (or before a reconnect)' }
    ])
    expect(drawn([{ kind: 'foreign', note: 'unknown', text: 'a' }])).toEqual([
      { actions: [], badges: ['unknown'], icon: 'corner-down-right', title: 'Queued behind a turn whose outcome is unknown' }
    ])
  })
})
