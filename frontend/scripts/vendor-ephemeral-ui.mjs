#!/usr/bin/env node
// Vendors kvnloo/ephemeral-ui's card catalog at one pinned commit into src/vendor/ephemeral-ui/:
// the repo's own kinds-*.js bundled as one script (run in a DOM sandbox at runtime, never rewritten),
// its data fixtures, and its stylesheets scoped under the card root so they cannot restyle the chat.
//   node scripts/vendor-ephemeral-ui.mjs /path/to/ephemeral-ui-checkout
import { execFileSync } from 'node:child_process'
import { copyFileSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { join, resolve } from 'node:path'

import { build } from 'esbuild'

import { TERN_BAD_MEDIA, TERN_BAD_SELECTOR, ternBody } from '../src/eui/ternCss.js'
import { root } from './ratchet.mjs'

export const PIN = '63e06b29ffb0d7c5b9d482abebc0312335897321'
const REGISTRIES = ['a', 'b', 'c', 'e', 'f', 't', 'i', 'infra', 'ops']
const CSS = ['styles.css', 'trace.css', 'intent.css', 'stats.css', 'ops.css', 'infra.css', 'flow.css']
// Public catalog data only. The trace, ops and intent fixtures are sanitized captures of the owner's
// own runs: they are read at runtime from the kit repo at PIN (sandbox.js), never republished here.
const DATA = ['apps.json', 'themes.json']
export const SCOPE = "[data-eui='card']"

/** Prefixes every selector with SCOPE; :root/html/body become the scope itself. Keyframes pass through. */
export function scopeCss(css) {
  let out = ''
  let i = 0
  const n = css.length

  while (i < n) {
    const open = css.indexOf('{', i)

    if (open < 0) { break }

    const head = css.slice(i, open).replace(/\/\*[\s\S]*?\*\//g, '').trim()
    const close = block(css, open)
    const body = css.slice(open + 1, close)

    if (/^@(media|supports|container|layer)/.test(head)) {
      if (!TERN_BAD_MEDIA.test(head)) { out += `${head}{${scopeCss(body)}}\n` }
    } else if (/^@keyframes/.test(head)) {
      out += `${head}{${body.replace(/\{([^{}]*)\}/g, (_, b) => `{${ternBody(b)}}`)}}\n`
    } else if (head.startsWith('@')) {
      out += `${head}{${body}}\n`
    } else if (!/::view-transition/.test(head)) {
      const sel = head.split(/,(?![^(]*\))/).filter(s => !TERN_BAD_SELECTOR.test(s)).map(s => scoped(s.trim())).filter(Boolean).join(',')

      if (sel) { out += `${sel}{${ternBody(body)}}\n` }
    }

    i = close + 1
  }

  return out
}

function block(css, open) {
  let depth = 0

  for (let j = open; j < css.length; j++) {
    if (css[j] === '{') { depth++ } else if (css[j] === '}' && --depth === 0) { return j }
  }

  return css.length
}

function scoped(sel) {
  if (!sel || sel === '*') { return sel === '*' ? `${SCOPE} *` : '' }
  // Theme switches and root-level hooks keep their condition on the card root.
  const rooted = sel.replace(/^(:root|html|body)(?![\w-])/, SCOPE)

  if (rooted !== sel) { return rooted.replace(/^(\[data-eui='card'\])\s+(body|html)(?![\w-])/, '$1') }
  if (/^\.dark(?![\w-])/.test(sel)) { return sel.replace(/^\.dark/, `${SCOPE}.dark`) }

  return `${SCOPE} ${sel}`
}

async function main() {
  const src = resolve(process.argv[2] ?? '/mnt/zer0models/github/ephemeral-ui')
  const head = execFileSync('git', ['-C', src, 'rev-parse', 'HEAD'], { encoding: 'utf8' }).trim()

  if (head !== PIN) { throw new Error(`ephemeral-ui checkout is ${head}, expected ${PIN}`) }

  const out = resolve(root, 'src/vendor/ephemeral-ui')
  mkdirSync(join(out, 'data'), { recursive: true })
  const imports = REGISTRIES.map(r => `import { KINDS_${r.toUpperCase()} } from ${JSON.stringify(join(src, `js/kinds-${r}.js`))};`).join('\n')
  const entry = `${imports}
import { rng, Run, motion } from ${JSON.stringify(join(src, 'js/motion.js'))};
import { loadApps, catalog } from ${JSON.stringify(join(src, 'js/shell.js'))};
import { state as theme } from ${JSON.stringify(join(src, 'js/themes.js'))};
globalThis.__EUI = { KINDS: { ${REGISTRIES.map(r => `...KINDS_${r.toUpperCase()}`).join(', ')} }, rng, Run, motion, loadApps, catalog, theme };`
  const result = await build({ stdin: { contents: entry, resolveDir: src, loader: 'js' }, bundle: true, format: 'iife', write: false, legalComments: 'none', logLevel: 'warning' })
  writeFileSync(join(out, 'kit.js'), `// Generated by scripts/vendor-ephemeral-ui.mjs from kvnloo/ephemeral-ui@${PIN}. Do not edit.\n${result.outputFiles[0].text}`)
  writeFileSync(join(out, 'kit.css'), `/* Generated from kvnloo/ephemeral-ui@${PIN} (${CSS.join(', ')}), scoped under ${SCOPE}. */\n${CSS.map(f => scopeCss(readFileSync(join(src, f), 'utf8'))).join('')}`)

  for (const f of DATA) { copyFileSync(join(src, 'data', f), join(out, 'data', f)) }

  const kinds = JSON.parse(readFileSync(join(src, 'schema/card.v0.json'), 'utf8')).properties.kind.enum
  writeFileSync(join(out, 'PIN.json'), `${JSON.stringify({ repo: 'kvnloo/ephemeral-ui', sha: PIN, remoteData: `https://raw.githubusercontent.com/kvnloo/ephemeral-ui/${PIN}/data/`, kinds }, null, 2)}\n`)
  console.log(`vendored ephemeral-ui@${PIN.slice(0, 12)}: ${kinds.length} schema kinds`)
}

if (import.meta.url === `file://${process.argv[1]}`) { await main() }
